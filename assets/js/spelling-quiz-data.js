const SPELL_PICK = { 1:4, 2:4, 3:4 };
const SPELL_TOTAL = 12;

function spellShuffle(arr) {
  var a = arr.slice();
  for (var i = a.length - 1; i > 0; i--) {
    var j = Math.floor(Math.random() * (i + 1));
    var t = a[i]; a[i] = a[j]; a[j] = t;
  }
  return a;
}

/* 난이도별로 정해진 개수를 뽑아 쉬운 것부터 냅니다. 각 문항에는 원래 번호(idx)를 달아 둡니다. */
function pickSpellQuestions() {
  var all = SPELL_QUESTIONS.map(function (q, i) {
    return { idx: i, diff: q.diff, q: q.q, correct: q.correct, wrong: q.wrong, why: q.why };
  });
  var picked = [];
  Object.keys(SPELL_PICK).forEach(function (d) {
    var pool = spellShuffle(all.filter(function (q) { return q.diff === Number(d); }));
    picked = picked.concat(pool.slice(0, SPELL_PICK[d]));
  });
  return spellShuffle(picked).sort(function (a, b) { return a.diff - b.diff; });
}

/* 문장 속 □ 자리에 낱말을 넣어 돌려줍니다 (html: true 면 강조 태그 포함) */
function fillSpell(q, word, html) {
  var w = html ? "<b>" + word + "</b>" : word;
  return q.split("□").join(w);
}

