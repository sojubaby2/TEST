  function daeunNotes(a) {
    if (!a.daeun) return [];
    const ys = a.yongsin.primary;
    const curOrder = a.currentDaeun && a.currentDaeun.item ? a.currentDaeun.item.order : -1;
    const nowAge = a.currentDaeun ? a.currentDaeun.age : -1;
    return a.daeun.list.map(function (it) {
      const parts = [];
      if (it.stemGod && GOD[it.stemGod]) parts.push(GOD[it.stemGod].mean);
      const stemEl = STEM_OF(it.stem), branchEl = BRANCH_OF(it.branch);
      const hasYongsin = (stemEl === ys || branchEl === ys);
      let text = parts.length ? parts[0] + "의 영역이 전면에 나오는 10년입니다." : "";
      if (it.stage) text += " 일간은 " + it.stage + " 단계에 놓입니다.";
      if (hasYongsin) text += " 도움이 되는 " + EL_LABEL[ys] + " 기운이 들어와 있어 흐름을 타기 수월한 구간이에요.";
      return {
        order: it.order, from: it.from, to: it.to,
        pillar: it.pillar, hanja: it.hanja,
        stemGod: it.stemGod, branchGod: it.branchGod, stage: it.stage,
        isNow: it.order === curOrder,
        isPast: nowAge > it.to,
        hasYongsin: hasYongsin,
        text: text.trim(),
      };
    });
  }

  function sectionYear(a) {
    // 올해의 간지를 입춘 기준으로 구해 세운을 봅니다
    const now = new Date();
    const ymp = SajuEngine.computeYearMonthPillar(
      now.getFullYear(), now.getMonth() + 1, now.getDate(), 12, 0);
    const pillar = ymp.yearPillar;
    const stem = pillar.charAt(0), branch = pillar.charAt(1);
    const sg = SajuEngine.tenGodOfStem(a.dayStem, stem);
    const bg = SajuEngine.tenGodOfBranch(a.dayStem, branch);
    const stage = SajuEngine.twelveStage(a.dayStem, branch);

    const paras = [];
    paras.push(
      "한 해의 기운을 <b>세운</b>이라고 합니다. 올해(" + ymp.sajuYear + "년, 입춘 기준)의 간지는 " +
      "<b>" + pillar + "</b>입니다. 당신의 일간 " + a.dayStem + eulReul(a.dayStem) + " 기준으로 보면 " +
      "천간은 <b>" + (sg || "-") + "</b>, 지지는 <b>" + (bg || "-") + "</b>에 해당합니다."
    );
    if (sg && GOD[sg]) {
      paras.push("올해는 " + GOD[sg].mean + "에 해당하는 영역이 두드러지는 해입니다. " + GOD[sg].many);
    }
    // 올해 오행이 용신인지
    const ysEl = a.yongsin.primary;
    if (STEM_OF(stem) === ysEl || BRANCH_OF(branch) === ysEl) {
      paras.push(
        "올해의 간지에는 당신에게 도움이 되는 <b>" + EL_LABEL[ysEl] + "</b> 기운이 들어 있습니다. " +
        "미뤄둔 일을 꺼내보기에 나쁘지 않은 해로 봅니다."
      );
    }
    if (stage) paras.push("일간이 올해의 지지에서 갖는 단계는 <b>" + stage + "</b>입니다. " + STAGE[stage]);

    // 올해 지지가 사주 지지와 만드는 관계
    const myBranches = a.cells.map(function (c) { return c.branch; });
    const rel = [];
    [["자","오"],["축","미"],["인","신"],["묘","유"],["진","술"],["사","해"]].forEach(function (p) {
      if ((p[0] === branch && myBranches.indexOf(p[1]) !== -1) ||
          (p[1] === branch && myBranches.indexOf(p[0]) !== -1)) {
        rel.push("올해의 지지 " + branch + "이(가) 사주의 지지와 <b>충</b>을 이룹니다. 변동과 이동이 잦아지는 해로 봤어요.");
      }
    });
    if (a.gongmang.indexOf(branch) !== -1) {
      rel.push("올해의 지지가 당신의 <b>공망</b>에 해당합니다. 분주한 것에 비해 손에 남는 것이 적게 느껴질 수 있는 해예요.");
    }
    return { paras:paras.concat(rel), pillar:pillar, sajuYear:ymp.sajuYear, stemGod:sg, branchGod:bg, stage:stage };
  }

