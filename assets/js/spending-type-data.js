function getSpendingTypeById(id) {
  return SPENDINGTYPE_RESULTS.find((r) => r.id === id);
}

/* 동점이면 답 모양에 따라 골고루 하나를 정합니다. 같은 답이면 늘 같은 결과예요. */
function tallyToSpendingTypeResult(tally) {
  const order = ["value", "flex", "exp", "saver", "giver"];
  let bestCount = -1;
  order.forEach((key) => { bestCount = Math.max(bestCount, tally[key] || 0); });
  const tied = order.filter((key) => (tally[key] || 0) === bestCount);
  let mix = 7;
  order.forEach((key, i) => { mix = (mix * 31 + (tally[key] || 0) * (i + 3)) % 9973; });
  return getSpendingTypeById(tied[mix % tied.length]);
}

