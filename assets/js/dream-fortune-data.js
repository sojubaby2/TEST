function normalizeDreamQuery(s) {
  return (s || "").toLowerCase().replace(/\s+/g, "").replace(/꿈$/, "").trim();
}

function getDreamById(id) {
  for (var i = 0; i < DREAM_LIST.length; i++) {
    if (DREAM_LIST[i].id === id) return DREAM_LIST[i];
  }
  return null;
}

function getDreamCategoryMeta(catId) {
  for (var i = 0; i < DREAM_CATEGORIES.length; i++) {
    if (DREAM_CATEGORIES[i].id === catId) return DREAM_CATEGORIES[i];
  }
  return { id: catId, label: catId, emoji: "✨" };
}

// 검색: 키워드/별칭에 쿼리가 포함되면 매치. 정확히 일치하는 키워드/별칭을 우선순위로 정렬.
function searchDreams(query) {
  var q = normalizeDreamQuery(query);
  if (!q) return [];
  var exact = [];
  var partial = [];
  DREAM_LIST.forEach(function (item) {
    var nk = normalizeDreamQuery(item.keyword);
    var aliasNorms = item.aliases.map(normalizeDreamQuery);
    var isExact = nk === q || aliasNorms.indexOf(q) !== -1;
    var isPartial =
      nk.indexOf(q) !== -1 ||
      aliasNorms.some(function (a) { return a.indexOf(q) !== -1; }) ||
      q.indexOf(nk) !== -1;
    if (isExact) {
      exact.push(item);
    } else if (isPartial) {
      partial.push(item);
    }
  });
  return exact.concat(partial);
}

function getDreamsByCategory(catId) {
  return DREAM_LIST.filter(function (item) {
    return item.category === catId;
  });
}
