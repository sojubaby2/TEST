  // withBatchim 은 받침이 있을 때 쓰는 쪽입니다. (예: josa("기", "은", "는") → "는")
  function josa(word, withBatchim, without) {
    if (!word) return without;
    // 괄호나 따옴표로 끝나면 그 앞의 글자를 봅니다
    let s = String(word).replace(/[)\]}"'·\s]+$/, "");
    const code = s.charCodeAt(s.length - 1);
    if (code < 0xac00 || code > 0xd7a3) return without;
    return ((code - 0xac00) % 28) !== 0 ? withBatchim : without;
  }
