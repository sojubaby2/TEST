/* 축마다 이어진 막대(양) 쪽 답이 절반 넘으면 1, 아니면 0. 4문항씩이라 2:2 동점이면
   마지막에 고른 답을 따름 (가장 최근 마음) */
function myGuaCode(answers) {
  function bit(axis) {
    const a = answers.filter((x) => x.axis === axis);
    const yang = a.filter((x) => x.yang === 1).length;
    if (yang * 2 > a.length) return "1";
    if (yang * 2 < a.length) return "0";
    return a.length ? String(a[a.length - 1].yang) : "0";
  }
  return bit("t") + bit("m") + bit("b");
}
