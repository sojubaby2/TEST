function tarotHashSeed(str) {
  let h = 0;
  for (let i = 0; i < str.length; i++) {
    h = (h * 31 + str.charCodeAt(i)) >>> 0;
  }
  return h;
}

function getTarotTodayDateStr() {
  const d = new Date();
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return y + "-" + m + "-" + day;
}

// 방문자별 고유 시드를 로컬스토리지에 저장해서, 같은 사람이 같은 날 다시 방문해도
// 같은 카드가 나오도록 함 (날짜가 바뀌면 자동으로 다른 카드로 갱신됨)
function getTarotVisitorSeed() {
  var KEY = "maumcatch_tarot_seed";
  try {
    var existing = localStorage.getItem(KEY);
    if (existing) return existing;
    var fresh = "v" + Date.now() + "-" + Math.floor(Math.random() * 1000000);
    localStorage.setItem(KEY, fresh);
    return fresh;
  } catch (e) {
    // 로컬스토리지를 못 쓰는 환경이면 날짜만으로 결정 (그날은 모두 같은 카드)
    return "no-storage";
  }
}

function getTodayTarotDraw() {
  const dateStr = getTarotTodayDateStr();
  const seed = getTarotVisitorSeed();
  const base = dateStr + "-" + seed;
  const cardIdx = tarotHashSeed(base + "-card") % TAROT_CARDS.length;
  const isReversed = tarotHashSeed(base + "-orientation") % 2 === 1;
  return {
    dateStr: dateStr,
    card: TAROT_CARDS[cardIdx],
    reversed: isReversed,
  };
}
