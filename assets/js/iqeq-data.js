const IQ_PICK = { 1:2, 2:3, 3:3, 4:2 };   // 난이도별로 뽑을 개수
const IQEQ_MAX_IQ = 10;
const IQEQ_MAX_EQ = IQEQ_EQ_QUESTIONS.length * 2;

const CAT_LABEL = { seq:"수열", num:"수리추리", logic:"언어추리", fig:"도형추리", spc:"공간지각" };

function iqShuffle(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const t = a[i]; a[i] = a[j]; a[j] = t;
  }
  return a;
}

/* 난이도별로 정해진 개수를 뽑되, 같은 갈래가 몰리지 않게 고릅니다 */
function pickIqQuestions() {
  const picked = [];
  const catUsed = {};

  Object.keys(IQ_PICK).forEach(function (d) {
    const pool = iqShuffle(IQ_QUESTIONS.filter(function (q) { return q.diff === Number(d); }));
    let need = IQ_PICK[d];
    // 1차: 아직 적게 나온 갈래부터
    pool.sort(function (a, b) { return (catUsed[a.cat] || 0) - (catUsed[b.cat] || 0); });
    for (let i = 0; i < pool.length && need > 0; i++) {
      picked.push(pool[i]);
      catUsed[pool[i].cat] = (catUsed[pool[i].cat] || 0) + 1;
      need--;
    }
  });

  // 쉬운 문제부터 나오도록 정렬하고, 보기 순서는 섞습니다
  return iqShuffle(picked)
    .sort(function (a, b) { return a.diff - b.diff; })
    .map(function (q) {
      return {
        type: "iq",
        cat: q.cat,
        diff: q.diff,
        text: q.text,
        fig: q.fig || null,
        why: q.why || "",
        options: iqShuffle(q.opts).map(function (o) {
          return { text: o.t || null, fig: o.f || null, score: o.ok ? 1 : 0 };
        }),
      };
    });
}

/* 퀴즈 한 판에 쓸 문항 (IQ 10 + EQ 6) */
function buildIqEqQuiz() {
  return pickIqQuestions().concat(IQEQ_EQ_QUESTIONS);
}

