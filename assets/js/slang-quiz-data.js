const SLANG_PICK = { 1:3, 2:4, 3:3 };
const SLANG_TOTAL = 10;

function shuffleArraySlang(arr) {
  var a = arr.slice();
  for (var i = a.length - 1; i > 0; i--) {
    var j = Math.floor(Math.random() * (i + 1));
    var t = a[i]; a[i] = a[j]; a[j] = t;
  }
  return a;
}

function pickSlangQuestions() {
  var picked = [];
  Object.keys(SLANG_PICK).forEach(function (d) {
    var pool = shuffleArraySlang(SLANG_QUESTIONS.filter(function (q) {
      return q.diff === Number(d);
    }));
    picked = picked.concat(pool.slice(0, SLANG_PICK[d]));
  });
  // 쉬운 것부터 나오게 하고, 같은 난이도 안에서는 순서를 섞습니다
  return shuffleArraySlang(picked).sort(function (a, b) { return a.diff - b.diff; });
}

