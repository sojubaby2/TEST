  function sectionGods(a) {
    const g = a.gods;
    const groups = g.groups;
    const order = ["비겁","식상","재성","관성","인성"];
    const total = order.reduce(function (s, k) { return s + groups[k]; }, 0) || 1;

    const rows = order.map(function (k) {
      return { key:k, count:groups[k], pct:Math.round(groups[k]/total*100), mean:GROUP_MEAN[k] };
    });
    const sorted = rows.slice().sort(function (x, y) { return y.count - x.count; });
    const top = sorted[0], bottom = sorted[sorted.length - 1];

    const paras = [];
    paras.push(
      "십신은 사주의 여덟 글자가 <b>일간과 어떤 관계인가</b>를 이름 붙인 것입니다. " +
      "가족 호칭처럼, 같은 글자도 누구를 기준으로 보느냐에 따라 이름이 달라져요. " +
      "이 분포를 보면 그 사람이 어느 영역에 에너지를 많이 쓰는지가 드러납니다."
    );
    paras.push(
      "당신의 사주에서 가장 두꺼운 것은 <b>" + top.key + "</b>(" + top.count + "개)입니다. " + GROUP_MEAN[top.key] + " " +
      "반대로 <b>" + bottom.key + "</b>은 " + (bottom.count === 0 ? "드러나지 않습니다." : bottom.count + "개로 가장 얇습니다.")
    );
    if (bottom.count === 0) {
      paras.push(
        "비어 있다고 나쁜 것은 아닙니다. 그 영역을 덜 쓰는 삶이라는 뜻으로 읽기도 하고, " +
        "오히려 그쪽에 매이지 않아 자유롭다고 보는 해석도 있어요. 다만 그 영역의 일이 닥쳤을 때 " +
        "스스로 해결하기보다 도움을 구하는 편이 수월합니다."
      );
    }

    const details = [];
    Object.keys(GOD).forEach(function (name) {
      const cnt = g.counts[name] || 0;
      if (cnt >= 2) details.push({ name:name, count:cnt, kind:"많음", text:GOD[name].many });
    });
    ["식신","상관","편재","정재","편관","정관","편인","정인"].forEach(function (name) {
      const cnt = g.counts[name] || 0;
      const groupCnt = groups[GOD[name].group];
      if (cnt === 0 && groupCnt === 0 && details.length < 7) {
        details.push({ name:name, count:0, kind:"없음", text:GOD[name].none });
      }
    });

    return { rows:rows, paras:paras, details:details, top:top, bottom:bottom };
  }

